#!/bin/bash
# Build zenoh-pico for ARM Cortex-M3 (QEMU mps2-an385)
#
# Cross-compiles zenoh-pico as a static library for bare-metal ARM Cortex-M3.
# This produces a standalone .a that serves as a build-readiness check for
# QEMU E2E tests. The actual linking is done by zpico-sys/build.rs via cc::Build.
#
# Usage:
#   ./scripts/qemu/build-zenoh-pico.sh [--clean]
#
# Output:
#   build/qemu-zenoh-pico/libzenohpico.a
#
# Prerequisites:
#   - arm-none-eabi-gcc toolchain

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
# phase-334 W2.b step 2 — RFC-0070 R3: one derivation, not a literal.
# shellcheck source=scripts/build/build-root.sh
source "$REPO_ROOT/scripts/build/build-root.sh"
BUILD_DIR="$(nros_build_dir "$NROS_KIND_QEMU_ZENOH_PICO")"
ZENOH_PICO_DIR="$REPO_ROOT/packages/rmw/zenoh/zpico-sys/zenoh-pico"
# The vendored tree's SOURCE root. Every path BELOW it is read from the shared
# manifest (see the selection block further down), never spelled here — that is
# what `check-zenoh-source-manifest`'s "no lane names a vendored path" asserts
# about this file.
ZENOH_PICO_SRC="$ZENOH_PICO_DIR/src"
ZENOH_SOURCE_MANIFEST="$REPO_ROOT/packages/rmw/zenoh/zpico-sys/zenoh-sources.txt"
C_DIR="$REPO_ROOT/packages/rmw/zenoh/zpico-sys/c"
PLATFORM_DIR="$C_DIR/platform"

# Parse arguments
if [ "$1" = "--clean" ]; then
    echo "Cleaning build directory..."
    rm -rf "$BUILD_DIR"
    echo "Done."
    exit 0
fi

# Check prerequisites
if ! command -v arm-none-eabi-gcc &>/dev/null; then
    echo "Error: arm-none-eabi-gcc not found"
    echo "Install with: sudo apt install gcc-arm-none-eabi"
    exit 1
fi

# Check zenoh-pico submodule
if [ ! -d "$ZENOH_PICO_DIR/include" ]; then
    echo "Error: zenoh-pico submodule not found"
    echo "Run: git submodule update --init"
    exit 1
fi

echo "Building zenoh-pico for ARM Cortex-M3..."

# Create build directory
mkdir -p "$BUILD_DIR"

# Generate version header (matches build.rs generate_embedded_version_header)
VERSION=$(cat "$ZENOH_PICO_DIR/version.txt" 2>/dev/null || echo "0.11.0")
MAJOR=$(echo "$VERSION" | cut -d. -f1)
MINOR=$(echo "$VERSION" | cut -d. -f2)
PATCH=$(echo "$VERSION" | cut -d. -f3)

mkdir -p "$BUILD_DIR/include"
cat > "$BUILD_DIR/include/zenoh-pico.h" << EOF
// Auto-generated version header for zenoh-pico
#ifndef ZENOH_PICO_H
#define ZENOH_PICO_H

#define ZENOH_PICO "$VERSION"
#define ZENOH_PICO_MAJOR $MAJOR
#define ZENOH_PICO_MINOR $MINOR
#define ZENOH_PICO_PATCH $PATCH
#define ZENOH_PICO_TWEAK 0

#include "zenoh-pico/api.h"

#endif // ZENOH_PICO_H
EOF

# Generate config header (matches build.rs generate_config_header)
mkdir -p "$BUILD_DIR/zenoh-config"
cat > "$BUILD_DIR/zenoh-config/zenoh_generic_config.h" << 'EOF'
/**
 * zenoh_generic_config.h - Generated by build-zenoh-pico.sh
 *
 * A MIRROR of what `nros_zpico_build::config_header()` generates for a
 * bare-metal target — issue 1096. It is a mirror and not a derivation because
 * that function resolves its inputs from cargo build-script environment (link
 * features, the RFC-0049 wire ladder, board knobs) that a standalone shell
 * script has no way to supply; reproducing the resolution here would be a
 * fourth statement of it, not one fewer.
 *
 * What it is NOT is an unwatched mirror, which is what it was: measured
 * 2026-09-05 it had drifted in ten places, including Z_TRANSPORT_LEASE (10000
 * against the 60000 issue 0906 moved it to) and Z_FEATURE_MATCHING /
 * Z_FEATURE_LOCAL_SUBSCRIBER / Z_FEATURE_LOCAL_QUERYABLE, which decide which
 * code compiles — so the readiness check was answering for a build nobody
 * performs. `check-zenoh-config-header-mirror` now compares this block against
 * that function's emissions, by macro NAME for every unconditional `#define`
 * and by VALUE wherever the Rust value is a literal.
 *
 * DO NOT EDIT BY HAND to make the gate pass: change `config_header()` and
 * mirror it here, in that order.
 */

